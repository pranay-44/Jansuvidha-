import { readFile, writeFile, mkdir, cp, stat, rename } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'csv-parse/sync';

const root = dirname(fileURLToPath(import.meta.url));
const types = { public_toilet: 'Public toilets', drinking_water: 'Drinking water', park: 'Parks' };

export function parseFacilities(csv) {
  const rows = parse(csv, { columns: true, bom: true, skip_empty_lines: true });
  if (!rows.length) throw new Error('CSV contains no facilities');
  const ids = new Set();
  return rows.map(row => {
    const id = row.facility_id?.trim();
    if (!id || !/^[A-Za-z0-9_-]+$/.test(id) || ids.has(id)) throw new Error(`Invalid or duplicate facility_id: ${id}`);
    ids.add(id);
    if (!row.name?.trim() || !Object.hasOwn(types, row.amenity_type)) throw new Error(`Missing name or unsupported amenity_type: ${id}`);
    if (!['unverified', 'usable', 'partial', 'unusable'].includes(row.field_status)) throw new Error(`Invalid field_status: ${id}`);
    const coordinate = (key, limit) => {
      if (!row[key]?.trim()) return null;
      const value = Number(row[key]);
      if (!Number.isFinite(value) || Math.abs(value) > limit) throw new Error(`Invalid ${key}: ${id}`);
      return value;
    };
    const photos = Object.keys(row).filter(k => /^photo_\d+_path$/.test(k)).sort().map(k => row[k]).filter(Boolean);
    for (const path of [...photos, row.cover_photo_path, row.geotag_photo_path].filter(Boolean)) {
      if (!/^photos\/(?:[A-Za-z0-9_-]+\/)*[A-Za-z0-9_-]+\.(?:jpg|jpeg|png|webp)$/i.test(path)) throw new Error(`Unsafe photo path: ${path}`);
    }
    if (Number(row.photo_count) !== photos.length || new Set(photos).size !== photos.length) throw new Error(`Photo count mismatch: ${id}`);
    if ([row.cover_photo_path, row.geotag_photo_path].some(p => p && !photos.includes(p))) throw new Error(`Cover/geotag missing from photo list: ${id}`);
    if (row.verified_at && !Number.isFinite(Date.parse(row.verified_at))) throw new Error(`Invalid verified_at: ${id}`);
    return {
      ...row, facility_id: id, id, name: row.name.trim(), type: types[row.amenity_type],
      latitude: coordinate('latitude', 90), longitude: coordinate('longitude', 180),
      ward: row.ward || null, status: row.field_status, verified: row.verified_at || null,
      hours: null, accessible: null, water: null, free: null, scores: [], photos,
    };
  });
}

export function upsertFacilities(existing, incoming) {
  const records = new Map(existing.map(f => [f.facility_id, f]));
  for (const facility of incoming) records.set(facility.facility_id, facility);
  return [...records.values()].sort((a, b) => a.facility_id.localeCompare(b.facility_id));
}

export async function importThane(source = resolve(root, 'public/data/thane')) {
  const canonical = resolve(root, 'public/data/thane');
  const output = resolve(root, 'dist/data/thane');
  const csv = await readFile(resolve(source, 'Thane_facilities.csv'), 'utf8');
  const incoming = parseFacilities(csv);
  for (const f of incoming) for (const photo of f.photos) {
    if (!(await stat(resolve(source, photo))).isFile()) throw new Error(`Missing photo: ${photo}`);
  }
  let existing = [];
  try { existing = JSON.parse(await readFile(resolve(canonical, 'facilities.json'), 'utf8')); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  const records = upsertFacilities(existing, incoming);
  await mkdir(canonical, { recursive: true });
  if (resolve(source) !== canonical) {
    await cp(resolve(source, 'photos'), resolve(canonical, 'photos'), { recursive: true });
    await writeFile(resolve(canonical, 'Thane_facilities.csv'), csv);
  }
  for (const f of records) for (const photo of f.photos) await stat(resolve(canonical, photo));
  await mkdir(output, { recursive: true });
  await cp(resolve(canonical, 'photos'), resolve(output, 'photos'), { recursive: true });
  await writeFile(resolve(output, 'Thane_facilities.csv'), csv);
  const json = JSON.stringify(records, null, 2) + '\n';
  await writeFile(resolve(canonical, 'facilities.json.tmp'), json);
  await rename(resolve(canonical, 'facilities.json.tmp'), resolve(canonical, 'facilities.json'));
  await writeFile(resolve(output, 'facilities.js.tmp'), `// Generated by npm run data:import; do not edit.\nexport default ${json.trim()};\n`);
  await rename(resolve(output, 'facilities.js.tmp'), resolve(output, 'facilities.js'));
  console.log(`Imported ${incoming.length} records; ${records.length} unique facilities; ${records.reduce((n, f) => n + f.photos.length, 0)} photos. Key: facility_id.`);
  return records;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await importThane(process.argv[2] ? resolve(process.argv[2]) : undefined);
}
